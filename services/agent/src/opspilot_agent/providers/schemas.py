"""Structured outputs the LLM is allowed to produce (docs/API_CONTRACT.md).

Every field bound here is a real constraint, not documentation: a provider
response is parsed through these models before anything downstream sees it, so
an over-long summary or an out-of-range confidence is a controlled validation
failure rather than data that quietly reaches a ticket.

`RetrievedChunk` lives in the retrieval layer, where its `score` comes from
pgvector. `ToolProposal` arrived with the graph in T19, as T15 anticipated.
"""

from __future__ import annotations

from enum import StrEnum

from pydantic import BaseModel, ConfigDict, Field


class TicketCategory(StrEnum):
    SHIPPING = "SHIPPING"
    BILLING = "BILLING"
    ACCOUNT = "ACCOUNT"
    OTHER = "OTHER"


class Urgency(StrEnum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"


class Classification(BaseModel):
    """docs/API_CONTRACT.md: category/urgency enums, summary <= 500, confidence [0,1]."""

    model_config = ConfigDict(extra="forbid")

    category: TicketCategory
    urgency: Urgency
    summary: str = Field(max_length=500)
    confidence: float = Field(ge=0.0, le=1.0)


class AgentActionType(StrEnum):
    """The only actions an agent may ever propose (docs/API_CONTRACT.md's internal API).

    An allowlist, not a description. AGENTS.md: "No arbitrary SQL, code, shell commands or URLs
    may be generated by the LLM and run as tools", and "AI cannot choose which permissions it
    has" — so a model can name one of these or nothing at all. Mirrors the Java enum of the same
    name; the database CHECK constraint is the shared contract.
    """

    ADD_INTERNAL_TAG = "ADD_INTERNAL_TAG"
    PUBLISH_INTERNAL_REPLY = "PUBLISH_INTERNAL_REPLY"


class ToolProposal(BaseModel):
    """docs/API_CONTRACT.md: tool_call_id, action_type enum, bounded arguments, rationale <= 500.

    A *proposal*, never an instruction. Nothing in this service executes one: the policy gate
    classifies it and, for a risky write, a human decides. `arguments` is deliberately a narrow
    mapping rather than free-form JSON — the per-action argument rules are checked by the policy
    gate, which is deterministic code rather than anything the model influences.
    """

    model_config = ConfigDict(extra="forbid")

    tool_call_id: str = Field(min_length=1, max_length=200)
    action_type: AgentActionType
    arguments: dict[str, str] = Field(default_factory=dict)
    rationale: str = Field(max_length=500)


class ReplyDraft(BaseModel):
    """docs/API_CONTRACT.md: body <= 4000 chars, citations referencing retrieved chunks.

    `source_citations` holds chunk *identifiers* rather than whole chunk objects. The agent cites
    what retrieval actually returned, so the authoritative text stays in the retrieval layer (T16)
    instead of being copied into — and potentially altered by — a model's own output.

    A draft is never published automatically. docs/PRODUCT_AND_ARCHITECTURE.md requires a human to
    approve the exact proposed text first, which is the approval flow in T21/T22.
    """

    model_config = ConfigDict(extra="forbid")

    body: str = Field(max_length=4000)
    source_citations: list[str] = Field(default_factory=list)
